func (r *InMemoryTestRepo) GetTest(testType entities.TestType) (*entities.Test, error) {
	test, exists := r.tests[testType]
	if !exists {
		return nil, fmt.Errorf("test %s not found", testType)
	}
	return test, nil
}

func (r *InMemoryTestRepo) GetAllTests() ([]entities.Test, error) {
	tests := make([]entities.Test, 0, len(r.tests))
	for _, test := range r.tests {
		tests = append(tests, *test)
	}
	return tests, nil
}
